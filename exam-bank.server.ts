function hashSeed(seed: string): number {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function seededShuffle<T>(items: readonly T[], seed: string): T[] {
  const copy = [...items];
  let h = hashSeed(seed);
  const rand = () => {
    h = Math.imul(h ^ (h >>> 16), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    h ^= h >>> 16;
    return (h >>> 0) / 4294967296;
  };
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    const left = copy[i] as T;
    copy[i] = copy[j] as T;
    copy[j] = left;
  }
  return copy;
}

export type PublicQuestion = { id: string; prompt: string; choices: string[] };

export function buildPaper(unitId: string): { title: string; minutes: number; questions: PublicQuestion[] } | null {
  const unit = findUnit(unitId);
  const questions = BANK[unitId];
  if (!unit || !questions || questions.length !== unit.exam.count) return null;
  return {
    title: unit.exam.title,
    minutes: unit.exam.minutes,
    questions: questions.map((question) => ({
      id: question.id,
      prompt: question.prompt,
      choices: seededShuffle(question.choices, question.id),
    })),
  };
}

export type ReviewItem = {
  id: string;
  prompt: string;
  choices: string[];
  chosen: string | null;
  correct: string;
  explanation: string;
  right: boolean;
};

export function gradeAnswers(
  unitId: string,
  answers: Record<string, string>,
): { score: number; total: number; review: ReviewItem[] } | null {
  const questions = BANK[unitId];
  const unit = findUnit(unitId);
  if (!unit || !questions) return null;
  let score = 0;
  const review = questions.map((question) => {
    const correct = question.choices[0];
    const chosen = typeof answers[question.id] === "string" ? answers[question.id] : null;
    const right = chosen === correct;
    if (right) score += 1;
    return {
      id: question.id,
      prompt: question.prompt,
      choices: seededShuffle(question.choices, question.id),
      chosen,
      correct,
      explanation: question.explanation,
      right,
    };
  });
  return { score, total: questions.length, review };
}
