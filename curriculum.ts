export type GradeId = "prep-1" | "prep-2" | "prep-3" | "sec-1" | "sec-2" | "sec-3";

export type BookSection = {
  heading: string;
  paragraphs: string[];
  formula?: string;
  example?: string;
};

export type Segment = {
  title: string;
  body: string;
  formula?: string;
  seconds: number;
};

export type Unit = {
  id: string;
  gradeId: GradeId;
  kicker: string;
  title: string;
  summary: string;
  book: { minutes: number; sections: BookSection[] };
  lesson: { minutes: number; segments: Segment[] };
  exam: { title: string; minutes: number; count: number };
};

export type Grade = {
  id: GradeId;
  stage: string;
  title: string;
  short: string;
  promise: string;
  units: Unit[];
};

function unit(
  id: string,
  gradeId: GradeId,
  kicker: string,
  title: string,
  summary: string,
  sections: BookSection[],
  segments: Segment[],
  examMinutes: number,
): Unit {
  const lessonSeconds = segments.reduce((sum, item) => sum + item.seconds, 0);
  return {
    id,
    gradeId,
    kicker,
    title,
    summary,
    book: { minutes: 11, sections },
    lesson: { minutes: Math.max(4, Math.round(lessonSeconds / 60)), segments },
    exam: { title: `امتحان ${title}`, minutes: examMinutes, count: 5 },
  };
}

